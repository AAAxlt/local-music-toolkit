def enc_chain(data, key):
    q_prev, c_prev = data[:8], qq_ekey.qqtea_encrypt_block(data[:8], key)
    out = bytearray(c_prev)
    for offset in range(8, len(data), 8):
        q = bytes(a ^ b for a, b in zip(data[offset:offset + 8], c_prev))
        c = bytes(a ^ b for a, b in zip(qq_ekey.qqtea_encrypt_block(q, key), q_prev))
        out += c
        q_prev, c_prev = q, c
    return bytes(out)


def body(size, pad=6, seed=0x31):
    value = bytearray(((seed + i * 29) & 0xFF) for i in range(size))
    value[0] = (value[0] & 0xF8) | pad
    return bytes(value)


def wrap(payload, pad=6):
    header = bytearray([0xA5] * (pad + 3))
    header[0] = (header[0] & 0xF8) | pad
    full = bytes(header) + payload + b"\x00" * 7
    assert len(full) % 8 == 0
    return full


def ekey_material(payload, simple=b"ABCDEFGH"):
    key = qq_ekey.interleave_tan_key(qq_ekey.DEFAULT_TAN_KEY, simple)
    return simple + enc_chain(wrap(payload), key)


def synthetic_ekey(payload):
    return base64.b64encode(ekey_material(payload))


def musicex_tag(tag_size=192, identifier="O8M0FILE0001", version=1):
    tag = bytearray(tag_size)
    struct.pack_into("<I", tag, 0x00, 123)
    struct.pack_into("<I", tag, 0x04, 0)
    struct.pack_into("<I", tag, 0x08, 0)
    encoded = identifier.encode("utf-16-le")[:0x3C]
    tag[0x0C:0x0C + len(encoded)] = encoded
    encoded = identifier.encode("utf-16-le")[:100]
    tag[0x48:0x48 + len(encoded)] = encoded
    struct.pack_into("<I", tag, 0xAC, 0)
    struct.pack_into("<I", tag, tag_size - 16, tag_size)
    struct.pack_into("<I", tag, tag_size - 12, version)
    tag[tag_size - 8:] = b"musicex\x00"
    return bytes(tag)


def qmc_page(payload, serial=1, sequence=0, header_type=0, granule=0, lacing=None):
    if lacing is None:
        lacing = [len(payload)]
    if sum(lacing) != len(payload):
        raise ValueError("lacing does not match payload")
    header = bytearray(b"OggS")
    header += bytes((0, header_type))
    header += granule.to_bytes(8, "little")
    header += serial.to_bytes(4, "little")
    header += sequence.to_bytes(4, "little")
    header += b"\x00\x00\x00\x00"
    header += bytes((len(lacing),))
    header += bytes(lacing)
    page = header + payload
    crc = ogg_page_crc(page)
    page[22:26] = crc.to_bytes(4, "little")
    return bytes(page)


class QmcGoldenTest(unittest.TestCase):
    def load(self, name):
        raw = (UPSTREAM_QMC / (name + "_raw.bin")).read_bytes()
        suffix = (UPSTREAM_QMC / (name + "_suffix.bin")).read_bytes()
        target = (UPSTREAM_QMC / (name + "_target.bin")).read_bytes()
        return raw, suffix, target

    @unittest.skipUnless(UPSTREAM_QMC.is_dir(), "pinned upstream QMC testdata is absent")
    def test_key_derivation_matches_upstream_keys(self):
        for name in ("mflac0_rc4", "mflac_map", "mflac_rc4", "mgg_map"):
            with self.subTest(name=name):
                raw = (UPSTREAM_QMC / (name + "_key_raw.bin")).read_bytes()
                want = (UPSTREAM_QMC / (name + "_key.bin")).read_bytes()
                self.assertEqual(qq_ekey.parse_ekey(raw), want)
                self.assertIn(len(want), (256, 512))

    @unittest.skipUnless(UPSTREAM_QMC.is_dir(), "pinned upstream QMC testdata is absent")
    def test_full_container_matches_upstream_targets(self):
        cases = {
            "qmc0_static": ".mp3",
            "mflac_map": ".flac",
            "mgg_map": ".ogg",
            "mflac0_rc4": ".flac",
            "mflac_rc4": ".flac",
        }
        for name, extension in cases.items():
            with self.subTest(name=name):
                raw, suffix, target = self.load(name)
                footer = legacy.parse_qmc_footer(raw + suffix)
                decoded = legacy.decrypt_qmc(raw + suffix, footer)
                self.assertEqual(decoded.data, target)
                self.assertEqual(decoded.extension, extension)
                self.assertIn(decoded.algorithm, ("qmc-static", "qmc-map", "qmc-rc4"))

    @unittest.skipUnless(UPSTREAM_QMC.is_dir(), "pinned upstream QMC testdata is absent")
    def test_offset_boundaries(self):
        for name in ("qmc0_static", "mflac_map", "mgg_map", "mflac0_rc4", "mflac_rc4"):
            raw, suffix, target = self.load(name)
            data = raw + suffix
            footer = legacy.parse_qmc_footer(data)
            key = footer.material if footer.material is not None else b""
            cipher = legacy.make_qmc_cipher(key)
            for offset in (0, 127, 128, 5119, 5120, 32767, 32768):
                with self.subTest(name=name, offset=offset):
                    piece = data[offset:offset + 137]
                    expected = target[offset:offset + 137]
                    self.assertEqual(cipher.decrypt(piece, offset), expected)

    def test_synthetic_vectors(self):
        payload = json.loads(VECTORS.read_text("utf-8"))
        self.assertIn("provenance", payload)
        for vector in payload["vectors"]:
            with self.subTest(name=vector["name"]):
                cipher = legacy.make_qmc_cipher(bytes.fromhex(vector.get("key_hex", "")))
                got = cipher.decrypt(
                    bytes.fromhex(vector["input_hex"]), vector["offset"]
                )
                self.assertEqual(got.hex(), vector["output_hex"])

    def test_static_rejects_non_audio(self):
        footer = legacy.QmcFooter("static", 32)
        with self.assertRaises(legacy.LegacyError) as caught:
            legacy.decrypt_qmc(b"\x00" * 32, footer)
        self.assertEqual(caught.exception.category, "qmc-key-mismatch")

    def test_rc4_zero_key_byte_guard(self):
        key = bytearray(range(64))
        key[0] = 0
        key[7] = 0
        cipher = legacy.make_qmc_cipher(bytes(key))
        self.assertEqual(len(cipher.decrypt(b"x" * 7000, 5120)), 7000)


class FooterTest(unittest.TestCase):
    def test_musicex_192_and_larger(self):
        for tag_size in (192, 256):
            with self.subTest(tag_size=tag_size):
                tag = musicex_tag(tag_size, "O8M0FILE%04d" % tag_size)
                data = b"AUDIO" * 10 + tag
                footer = legacy.parse_qmc_footer(data)
                self.assertEqual(footer.kind, "musicex")
                self.assertEqual(footer.audio_length, 50)
                self.assertEqual(footer.tag_size, tag_size)
                self.assertEqual(footer.tag_count, 1)
                self.assertEqual(footer.identifier, "O8M0FILE%04d" % tag_size)

    def test_musicex_bounds(self):
        valid = musicex_tag(192)
        cases = {
            "too-short": b"x",
            "bad-version": b"AUDIO" * 10 + musicex_tag(192, version=2),
            "small-tag": b"AUDIO" * 10 + valid[:-16] + struct.pack("<II", 0x20, 1) + b"musicex\x00",
            "oversized": b"AUDIO" * 10 + valid[:-16]
                         + struct.pack("<II", 0xFFFFFFFF, 1) + b"musicex\x00",
        }
        for label, data in cases.items():
            with self.subTest(label=label):
                with self.assertRaises(legacy.LegacyError):
                    legacy.parse_qmc_footer(data)

    def test_musicex_repeated_same_identifier_tails_stripped(self):
        key = bytes((i * 13 + 7) & 0xFF for i in range(256))
        plain = b"OggS" + bytes(range(128))
        audio = legacy.make_qmc_cipher(key).decrypt(plain, 0)
        identifier = "Tianya_O4M0_320"
        first = bytearray(musicex_tag(192, identifier))
        second = bytearray(musicex_tag(192, identifier))
        third = bytearray(musicex_tag(192, identifier))
        first[0x20:0x24] = b"\x11\x22\x33\x44"
        second[0x20:0x24] = b"\x55\x66\x77\x88"
        third[0x20:0x24] = b"\x99\xaa\xbb\xcc"
        for tags, expected_count in (((second, first), 2), ((third, second, first), 3)):
            with self.subTest(tags=expected_count):
                data = audio + b"".join(tags)
                footer = legacy.parse_qmc_footer(data)
                self.assertEqual(footer.kind, "musicex")
                self.assertEqual(footer.tag_count, expected_count)
                self.assertEqual(footer.audio_length, len(audio))
                self.assertEqual(footer.identifier, identifier)
                decoded = legacy.decrypt_qmc(data, footer, key)
                self.assertEqual(decoded.data, plain)

    def test_musicex_repeated_tail_requires_identical_identifier(self):
        key = bytes((i * 5 + 1) & 0xFF for i in range(64))
        audio = b"OggS" + b"audio" * 8
        first = musicex_tag(192, "DIFFERENT_FILE")
        last = musicex_tag(192, "KEEP_FILE")
        footer = legacy.parse_qmc_footer(audio + first + last)
        self.assertEqual(footer.tag_count, 1)
        self.assertEqual(footer.audio_length, len(audio) + 192)
        self.assertEqual(footer.identifier, "KEEP_FILE")

    def test_xiami_m4a_and_sniffed_mp4_are_one_family(self):
        plain = (b"\x00\x00\x00\x20ftypisom\x00\x00\x02\x00isomiso2"
                 + bytes(range(48)))
        start = 0
        mask = 0x5A
        encrypted = bytes(value ^ mask for value in plain)
        header = bytearray(b"ifmt" + b" A4M" + b"\xfe\xfe\xfe\xfe")
        header += start.to_bytes(3, "little") + bytes((mask,))
        decoded = legacy.decode_xiami(bytes(header) + encrypted)
        self.assertEqual(decoded.data, plain)
        self.assertEqual(decoded.extension, ".m4a")

        bad = bytearray(b"ifmt" + b"FLAC" + b"\xfe\xfe\xfe\xfe")
        bad += (0).to_bytes(3, "little") + b"\x00"
        with self.assertRaises(legacy.LegacyError) as caught:
            legacy.decode_xiami(bytes(bad) + b"OggS" + b"x" * 20)
        self.assertEqual(caught.exception.category, "xiami-format-mismatch")

    def test_qtag_valid_and_bad(self):
        payload = body(504)
        raw_key = synthetic_ekey(payload)
        meta = raw_key + b",309058164,2"
        audio = b"fLaC" + b"x" * 60
        data = audio + meta + len(meta).to_bytes(4, "big") + b"QTag"
        footer = legacy.parse_qmc_footer(data)
        self.assertEqual(footer.kind, "qtag")
        self.assertEqual(footer.audio_length, len(audio))
        self.assertEqual(footer.material, b"ABCDEFGH" + payload)

        for bad in (
            audio + meta + (len(meta) + 1).to_bytes(4, "big") + b"QTag",
            audio + raw_key + b",not-an-int,2" + len(raw_key + b",not-an-int,2").to_bytes(4, "big") + b"QTag",
            audio + b"!!!!,1,2" + len(b"!!!!,1,2").to_bytes(4, "big") + b"QTag",
        ):
            with self.subTest(length=len(bad)):
                with self.assertRaises(legacy.LegacyError):
                    legacy.parse_qmc_footer(bad)

        stag = audio + b"xxxx" + b"STag"
        with self.assertRaises(legacy.LegacyError) as caught:
            legacy.parse_qmc_footer(stag)
        self.assertEqual(caught.exception.category, "qmc-stag-unsupported")

    def test_raw_key_and_static_footer_forms(self):
        payload = body(504)
        raw_key = synthetic_ekey(payload)
        material = qq_ekey.parse_ekey(raw_key)
        audio = b"OggS" + b"x" * 100
        data = audio + raw_key + len(raw_key).to_bytes(4, "little")
        footer = legacy.parse_qmc_footer(data)
        self.assertEqual(footer.kind, "rawkey")
        self.assertEqual(footer.material, material)
        self.assertEqual(footer.audio_length, len(audio))

        static = b"audio-data" + struct.pack("<I", 0xFFFFFFFF)
        self.assertEqual(legacy.parse_qmc_footer(static).kind, "static")
        zero = b"audio-data" + struct.pack("<I", 0)
        self.assertEqual(legacy.parse_qmc_footer(zero).kind, "static")
        truncated = b"audio-data" + struct.pack("<I", 100)
        with self.assertRaises(legacy.LegacyError) as caught:
            legacy.parse_qmc_footer(truncated)
        self.assertEqual(caught.exception.category, "qmc-footer-truncated")


class LegacyContainerTest(unittest.TestCase):
    def test_kwm_roundtrip_and_header_parse(self):
        plain = b"fLaC" + bytes(range(256)) * 2
        header = bytearray(0x400)
        header[:16] = legacy.KWM_HEADER_1
        key = bytes.fromhex("0102030405060708")
        header[0x18:0x20] = key
        header[0x30:0x38] = b"192flac\x00"
        mask = legacy._kwm_mask(key)
        encrypted = bytes(value ^ mask[i & 0x1F] for i, value in enumerate(plain))
        decoded = legacy.decode_kwm(bytes(header) + encrypted)
        self.assertEqual(decoded.data, plain)
        self.assertEqual(decoded.extension, ".flac")
        self.assertEqual(legacy._kwm_type(b"128mp3\x00\x00"), (128, ".mp3"))
        self.assertEqual(legacy._kwm_type(b"128\x00\x00\x00\x00\x00"), (128, ""))
        self.assertEqual(legacy._kwm_type(b"ape\x00\x00\x00\x00\x00"), (0, ".ape"))

    def test_xiami_roundtrip(self):
        plain = b"fLaC" + bytes(range(200))
        start = 5
        mask = 0x5A
        encrypted = bytearray(plain)
        for i in range(start, len(encrypted)):
            encrypted[i] ^= mask
        header = bytearray(b"ifmt" + b"FLAC" + b"\xfe\xfe\xfe\xfe")
        header += start.to_bytes(3, "little") + bytes((mask,))
        decoded = legacy.decode_xiami(bytes(header) + bytes(encrypted))
        self.assertEqual(decoded.data, plain)
        self.assertEqual(decoded.extension, ".flac")

    def test_ximalaya_x2m_and_x3m(self):
        for label, name, checksum, key in (
            ("x2m", "x2m_scramble_table.bin", legacy.X2M_TABLE_SHA256, legacy.X2M_KEY),
            ("x3m", "x3m_scramble_table.bin", legacy.X3M_TABLE_SHA256, legacy.X3M_KEY),
        ):
            with self.subTest(label=label):
                table = legacy._load_table(name, checksum)
                plain_header = bytearray(1024)
                plain_header[:4] = b"OggS"
                plain_header[4:64] = bytes(range(60))
                encrypted = bytearray(1024)
                for dst in range(1024):
                    encrypted[table[dst]] = plain_header[dst] ^ key[dst % len(key)]
                rest = b"tail-bytes"
                decoded = legacy.decode_ximalaya(bytes(encrypted) + rest)
                self.assertEqual(decoded.data, bytes(plain_header) + rest)
                self.assertEqual(decoded.extension, ".ogg")
                self.assertEqual(decoded.algorithm, label + "-scramble")

    def test_tm_header_restore(self):
        data = b"QQMU" + b"\x00\x00\x00\x00" + b"\x00\x00\x00\x20ftypM4A " + b"\x00" * 20
        decoded = legacy.decode_tm(data)
        self.assertEqual(decoded.data[:8], legacy.TM_REPLACEMENT)
        self.assertEqual(decoded.data[8:], data[8:])
        self.assertEqual(decoded.extension, ".m4a")

    def _kgm_header(self, version=3, slot=1, offset=0x3C):
        header = bytearray(0x3C)
        header[:16] = legacy.KGM_HEADER
        struct.pack_into("<I", header, 0x10, offset)
        struct.pack_into("<I", header, 0x14, version)
        struct.pack_into("<I", header, 0x18, slot)
        header[0x1C:0x2C] = bytes(range(16))
        header[0x2C:0x3C] = bytes(range(16, 32))
        return bytes(header)

    def _kgm_encrypt(self, plain, header):
        slot_box = legacy._kugou_md5(legacy._KGM_V3_SLOT_KEYS[1])
        file_box = legacy._kugou_md5(header[0x2C:0x3C]) + b"\x6b"
        inverse = {value ^ ((value << 4) & 0xFF): value for value in range(256)}
        out = bytearray(len(plain))
        for i, value in enumerate(plain):
            # Upstream seeks to AudioOffset and then starts cipher offset at 0;
            # the transform is payload-relative, not absolute file offset.
            value ^= legacy._xor_collapse(i)
            value ^= slot_box[i % len(slot_box)]
            value = inverse[value]
            value ^= file_box[i % len(file_box)]
            out[i] = value
        return bytes(out)

    def test_kgm_v3_slot1_roundtrip(self):
        plain = b"fLaC" + bytes(range(128))
        for audio_offset in (0x3C, 0x40):
            with self.subTest(audio_offset=audio_offset):
                header = self._kgm_header(offset=audio_offset)
                cipher = self._kgm_encrypt(plain, header)
                data = header + b"\x00" * (audio_offset - len(header)) + cipher
                decoded = legacy.decode_kgm(data)
                self.assertEqual(decoded.data, plain)
                self.assertEqual(decoded.extension, ".flac")
                self.assertEqual(decoded.algorithm, "kgm-v3-slot1")

    def test_kgm_v3_literal_payload_relative_vector(self):
        # Frozen literal ciphertext for b"fLaC" + bytes(range(12)) under the
        # v3 slot 1 / key bytes 0x10..0x1f transform with payload offset 0.
        # The same 16 payload bytes must decode identically at AudioOffset
        # 0x3c and 0x40; an absolute-offset implementation fails both.
        plain = b"fLaC" + bytes(range(12))
        cipher = bytes.fromhex("4f58f25da9b4244aa33e3d8d514d2e65")
        for audio_offset in (0x3C, 0x40):
            with self.subTest(audio_offset=audio_offset):
                header = self._kgm_header(offset=audio_offset)
                data = header + b"\x00" * (audio_offset - len(header)) + cipher
                self.assertEqual(legacy.decode_kgm(data).data, plain)

    def test_kgm_v5_and_unknown_versions_are_explicit(self):
        for version, category in (
            (5, "kgm-v5-db-required"),
            (4, "kgm-version-unsupported"),
        ):
            with self.subTest(version=version):
                header = self._kgm_header(version=version)
                with self.assertRaises(legacy.LegacyError) as caught:
                    legacy.decode_kgm(header + b"payload")
                self.assertEqual(caught.exception.category, category)
        with self.assertRaises(legacy.LegacyError) as caught:
            legacy.decode_kgm(self._kgm_header(slot=2) + b"payload")
        self.assertEqual(caught.exception.category, "kgm-slot-unsupported")
        with self.assertRaises(legacy.LegacyError) as caught:
            legacy.decode_kgm(self._kgm_header(offset=0x20) + b"payload")
        self.assertEqual(caught.exception.category, "kgm-offset-invalid")

    def test_output_names_and_preview(self):
        self.assertEqual(legacy.output_name("song.mgg2.flac", ".ogg"), "song.ogg")
        self.assertEqual(legacy.output_name("song.mflac0", ".flac"), "song.flac")
        self.assertEqual(legacy.output_name("song.qmc0", ".mp3"), "song.mp3")
        self.assertEqual(legacy.output_name("song.kgm.flac", ".flac"), "song.flac")
        self.assertEqual(legacy.output_name("song.x2m", ".m4a"), "song.m4a")
        self.assertEqual(legacy.output_name("song.bin", ".flac"), "song.flac")
        self.assertEqual(legacy.output_name("song", ".ogg"), "song.ogg")
        self.assertEqual(
            legacy.preview_kind("a.mgg", b"\x00" * 16, b"\x00" * 16), "qmc"
        )
        self.assertEqual(
            legacy.preview_kind("a.bin", b"\x00" * 16, b"x" * 4 + b"QTag"), "qmc"
        )
        self.assertIsNone(
            legacy.preview_kind("a.txt", b"\x00" * 16, b"\x00" * 16)
        )


class OggValidationTest(unittest.TestCase):
    def write(self, data):
        handle = tempfile.NamedTemporaryFile(delete=False)
        handle.write(data)
        handle.close()
        self.addCleanup(lambda: os.path.exists(handle.name) and os.unlink(handle.name))
        return handle.name

    def pages(self):
        first = qmc_page(b"\x01", serial=7, sequence=0, header_type=2, granule=0)
        second = qmc_page(b"abc", serial=7, sequence=1, header_type=0, granule=11)
        last = qmc_page(b"", serial=7, sequence=2, header_type=4, granule=11)
        return first, second, last

    def test_valid_stream_and_crc(self):
        first, second, last = self.pages()
        self.assertTrue(validate_ogg_stream(self.write(first + second + last)))
        self.assertEqual(ogg_page_crc(first[:22] + b"\x00\x00\x00\x00" + first[26:]), int.from_bytes(first[22:26], "little"))

    def test_truncation_crc_sequence_and_eos(self):
        first, second, last = self.pages()
        cases = {
            "truncated": first + second + last[:-1],
            "bad-crc": first + second[:-1] + bytes((second[-1] ^ 1,)) + last,
            "bad-sequence": first + qmc_page(b"abc", serial=7, sequence=2, granule=11) + last,
            "missing-eos": first + second,
            "missing-bos": qmc_page(b"\x01", serial=7, sequence=0, granule=0) + second + last,
            "repeated-bos": first + qmc_page(b"abc", serial=7, sequence=1,
                                             header_type=2, granule=11) + last,
            "page-after-eos": first + second + last + qmc_page(b"", serial=7, sequence=3,
                                                               granule=11),
            "reserved-flag": qmc_page(b"\x01", serial=7, sequence=0, header_type=10,
                                      granule=0) + second + last,
            "continued-missing": first + qmc_page(b"abc", serial=7, sequence=1, header_type=1, granule=11) + last,
            "eos-unfinished-packet": first + qmc_page(b"x" * 255, serial=7, sequence=1, header_type=4,
                                                       granule=11, lacing=[255]),
        }
        for label, data in cases.items():
            with self.subTest(label=label):
                with self.assertRaises(ValueError):
                    validate_ogg_stream(self.write(data))


